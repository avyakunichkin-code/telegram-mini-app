import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
const root = new URL('./', import.meta.url)
mkdirSync(new URL('assets/', root), { recursive: true })
for (const weight of [400, 700]) {
  const name = `manrope-cyrillic-${weight}-normal.woff2`
  copyFileSync(new URL(`../../../frontend-react/src/assets/fonts/${name}`, root), new URL(`assets/${name}`, root))
}
writeFileSync(new URL('lab-base.css', root), '/* Auto-generated by sync-lab.mjs; do not edit. */\n' + readFileSync(new URL('styles.css', root), 'utf8'))
