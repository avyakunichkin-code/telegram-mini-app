import { test, expect } from '@playwright/test'

async function seed(page) {
  await page.goto('/')
  await page.getByLabel('E-mail').fill(`decision-${Date.now()}-${Math.random().toString(16).slice(2)}@example.com`)
  await page.getByRole('button',{name:'Получить код'}).click()
  await page.getByLabel('6 цифр').fill((await page.locator('.stub b').innerText()).trim())
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Войти',exact:true}).click()
  await page.getByRole('button',{name:/Как у нас дела в целом/}).waitFor()
  const id=await page.evaluate(async()=>{
    const call=async(method,path,body)=>{
      const response=await fetch(path,{method,headers:{'Content-Type':'application/json',Authorization:`Bearer ${localStorage.getItem('plan.token')}`},body:body&&JSON.stringify(body)})
      if(!response.ok)throw Error('Seed failed '+response.status)
      return response.json()
    }
    const members=await call('PUT','/api/household/members',[{label:'Я',role:'adult'}])
    const ck=await call('POST','/api/checkups',{entry_question:'overview'})
    await call('PUT',`/api/checkups/${ck.id}/sections/incomes`,[{member_id:members[0].id,amount:{min:90000,max:120000}}])
    await call('PUT',`/api/checkups/${ck.id}/sections/expenses`,[{category_key:'life',amount:{min:95000,max:95000}}])
    await call('PUT',`/api/checkups/${ck.id}/sections/savings`,[{kind:'account',amount:{min:30000,max:30000},is_safety_fund:true}])
    return ck.id
  })
  await page.reload();await page.locator('.precision-refine').waitFor()
  return id
}
async function saved(page,id) {
  return page.evaluate(async id=>(await fetch(`/api/checkups/${id}`,{headers:{Authorization:`Bearer ${localStorage.getItem('plan.token')}`}})).json(),id)
}

test('A: unfinished input survives reload; server conflict requires a choice; logout clears snapshot',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const id=await seed(page)
  const min=page.getByLabel('Сумма в месяц: от',{exact:true})
  await min.fill('91000')
  await expect.poll(()=>page.evaluate(()=>!!sessionStorage.getItem('plan.unsaved-section.v1'))).toBe(true)
  await min.fill('90000')
  await expect.poll(()=>page.evaluate(()=>sessionStorage.getItem('plan.unsaved-section.v1'))).toBeNull()
  await page.reload()
  await expect(min).toHaveValue('90000')
  await expect(page.getByText('Вы продолжаете с того же места')).not.toBeVisible()
  await min.fill('')
  await expect.poll(()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('plan.unsaved-section.v1')||'null')?.rows[0]?.amount.min)).toBe('')
  await page.reload()
  await expect(page.getByText('Вы продолжаете с того же места')).toBeVisible()
  await expect(min).toHaveValue('')
  await min.fill('91000')
  await expect.poll(()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('plan.unsaved-section.v1')||'null')?.rows[0]?.amount.min)).toBe(91000)
  await page.evaluate(async id=>{
    const headers={'Content-Type':'application/json',Authorization:`Bearer ${localStorage.getItem('plan.token')}`}
    const ck=await(await fetch(`/api/checkups/${id}`,{headers})).json()
    ck.data.incomes[0].amount.min=92000
    await fetch(`/api/checkups/${id}/sections/incomes`,{method:'PUT',headers,body:JSON.stringify(ck.data.incomes)})
  },id)
  await page.reload()
  await expect(page.getByText('Сохранённые данные изменились')).toBeVisible()
  await page.getByRole('button',{name:'Продолжить с моим вводом'}).click()
  await expect(min).toHaveValue('91000')
  await page.getByRole('button',{name:'Сохранить и к разбору'}).click()
  await page.locator('.atlas-report').waitFor()
  expect(Number((await saved(page,id)).data.incomes[0].amount.min)).toBe(91000)
  expect(await page.evaluate(()=>sessionStorage.getItem('plan.unsaved-section.v1'))).toBeNull()
  await page.getByRole('button',{name:'Данные',exact:true}).click()
  await min.fill('93000')
  await expect.poll(()=>page.evaluate(()=>!!sessionStorage.getItem('plan.unsaved-section.v1'))).toBe(true)
  await page.getByRole('button',{name:'Профиль',exact:true}).click()
  await page.getByRole('button',{name:'Выйти',exact:true}).click()
  expect(await page.evaluate(()=>sessionStorage.getItem('plan.unsaved-section.v1'))).toBeNull()
  expect(errors).toEqual([])
  await page.screenshot({path:info.outputPath('logout.png'),fullPage:true})
})

test('A: live sensitivity and reserve preview leave the checkup unchanged, offline blocks new calculation',async({page,context},info)=>{
  const id=await seed(page),before=await saved(page,id)
  await page.getByRole('button',{name:'Разбор',exact:true}).click()
  await page.getByRole('button',{name:'Проверить влияние диапазона'}).click()
  await expect(page.locator('.decision-ends').first()).toContainText('−5')
  await expect(page.locator('.decision-ends').first()).toContainText('25')
  await page.getByRole('button',{name:'Проверить перевод',exact:true}).click()
  await expect(page.getByText('Дополнительный резерв за 12 месяцев')).toBeVisible()
  await expect(page.locator('.decision-value')).toContainText('60 000')
  expect(await saved(page,id)).toEqual(before)
  await page.getByLabel('Перевод в резерв каждый месяц, ₽').fill('1000000')
  await page.getByRole('button',{name:'Проверить перевод',exact:true}).click()
  await expect(page.getByText(/Не хватает денег для заданного перевода с 1-го/)).toBeVisible()
  await page.getByRole('button',{name:'Сбросить сценарий'}).click()
  await expect(page.getByLabel('Перевод в резерв каждый месяц, ₽')).toHaveValue('0')
  await page.getByRole('button',{name:'Данные',exact:true}).click()
  await page.getByLabel('Сумма в месяц: от',{exact:true}).fill('91000')
  await expect.poll(()=>page.evaluate(()=>!!sessionStorage.getItem('plan.unsaved-section.v1'))).toBe(true)
  await page.getByRole('button',{name:'Разбор',exact:true}).click()
  await page.getByRole('button',{name:'Получить итоговый разбор'}).click()
  await expect(page.getByRole('button',{name:'Новый чекап',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>sessionStorage.getItem('plan.unsaved-section.v1'))).toBeNull()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('decision-a.png'),fullPage:true})
  await context.setOffline(true)
  await expect(page.getByRole('button',{name:'Проверить перевод',exact:true})).toBeDisabled()
  await context.setOffline(false)
})
