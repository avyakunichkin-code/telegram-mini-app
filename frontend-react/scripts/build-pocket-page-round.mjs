import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const round = path.resolve(frontend, '../design-lab/dashboard/pocket-page-round');
const base = process.env.POCKET_QA_URL || 'http://127.0.0.1:5184';
fs.mkdirSync(path.join(round, 'assets'), { recursive: true });
function localAsset(url) {
  if (!url || /^(data:|#)/.test(url)) return url;
  const pathname = decodeURIComponent(new URL(url, base).pathname);
  if (!pathname.startsWith('/src/assets/')) return url;
  const source = path.resolve(frontend, `.${pathname}`);
  if (!source.startsWith(path.join(frontend, 'src/assets') + path.sep)) throw new Error('Asset outside frontend');
  const name = path.basename(source);
  fs.copyFileSync(source, path.join(round, 'assets', name));
  return `./assets/${name}`;
}
function rewriteHTML(html) {
  return html.replace(/\b(src|srcset)="([^"]*)"/g, (_, attr, value) => {
    const rewritten = attr === 'src' ? localAsset(value) : value.split(',').map(part => {
      const [url, ...tail] = part.trim().split(/\s+/); return [localAsset(url), ...tail].join(' ');
    }).join(', ');
    return `${attr}="${rewritten}"`;
  });
}
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--no-proxy-server'] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/#/dev/mqx`);
  const demo = page.locator('[data-catalog-demo="pocket-board"]');
  await demo.locator('.mqx-pocket-hero').waitFor();
  await page.evaluate(() => {
    const demo = document.querySelector('[data-catalog-demo="pocket-board"]');
    const parent = demo.closest('.mqx-catalog-section');
    for (const section of document.querySelectorAll('.mqx-catalog-section')) if (section !== parent) section.style.display = 'none';
  });
  await page.evaluate(() => document.fonts.ready);
  await demo.scrollIntoViewIfNeeded();
  const reference = {};
  const capture = async name => { reference[name] = rewriteHTML(await demo.locator('.mqx-pocket').evaluate(el => el.outerHTML)); };
  await capture('ready');
  fs.mkdirSync(path.join(round, 'qa'), { recursive: true });
  await demo.locator('.mqx-pocket').screenshot({ path: path.join(round, 'qa/mobile-ready.png') });
  const before = await demo.locator('.mqx-bg-needs').boundingBox();
  const ticketBefore = await demo.locator('.mqx-pocket-ticket--salary').boundingBox();
  await demo.getByRole('button', { name: 'Зарплата, получить', exact: true }).click();
  await demo.getByRole('button', { name: 'Зарплата, уже получена' }).waitFor();
  const after = await demo.locator('.mqx-bg-needs').boundingBox();
  const ticketAfter = await demo.locator('.mqx-pocket-ticket--salary').boundingBox();
  if (Math.abs(before.height - after.height) > .5 || Math.abs(ticketBefore.height - ticketAfter.height) > .5) throw new Error('Salary or needs height changed');
  await capture('paid');
  await demo.locator('.mqx-pocket').screenshot({ path: path.join(round, 'qa/mobile-paid.png') });
  await demo.locator('select').selectOption('risk'); await capture('risk');
  await demo.locator('select').selectOption('large'); await capture('large');
  await demo.locator('select').selectOption('low'); await capture('low');
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await demo.locator('select').selectOption('normal');
    await demo.locator('.mqx-pocket').screenshot({ path: path.join(round, `qa/width-${width}.png`) });
    const overflow = await demo.locator('.mqx-pocket-hero,.mqx-pocket-ticket').evaluateAll(nodes => nodes.some(el => el.scrollWidth > el.clientWidth + 1));
    if (overflow) throw new Error(`Pocket components overflow at ${width}px`);
  }
  const css = (await page.locator('style[data-vite-dev-id]').allTextContents()).join('\n').replace(/url\((['"]?)([^)'"\s]+)\1\)/g, (_, quote, url) => `url("${localAsset(url)}")`);
  fs.writeFileSync(path.join(round, 'runtime.css'), css);
  fs.writeFileSync(path.join(round, 'lab-base.css'), '/* Auto-generated by build-pocket-page-round.mjs from native runtime. */\n' + css);
  fs.writeFileSync(path.join(round, 'reference.js'), `window.POCKET_REFERENCE = ${JSON.stringify(reference)};\n`);
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('OK: native Pocket Board snapshot (ready/paid/risk/large); salary height + needs position stable.');
} finally { await browser.close(); }
