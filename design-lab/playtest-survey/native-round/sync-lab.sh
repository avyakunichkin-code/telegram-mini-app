#!/usr/bin/env bash
set -euo pipefail
ROUND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$ROUND/../../.." && pwd)"
mkdir -p "$ROUND/assets/fonts"
cp "$REPO/frontend-react/src/assets/fonts/"nunito-*.woff2 "$REPO/frontend-react/src/assets/fonts/"manrope-*.woff2 "$ROUND/assets/fonts/"
cp "$REPO/frontend-react/src/assets/guides/coin-welcome-avatar.webp" "$ROUND/assets/monetka.webp"
cp "$REPO/frontend-react/src/utils/playtestSurvey.js" "$ROUND/survey-questions.js"
{
  printf '/* Auto-generated by sync-lab.sh; sources: production fonts.css + tokens.css. */\n'
  sed 's#../assets/fonts/#./assets/fonts/#g' "$REPO/frontend-react/src/styles/fonts.css"
  printf '\n'
  sed '1s/^\xEF\xBB\xBF//' "$REPO/frontend-react/src/styles/tokens.css"
} > "$ROUND/lab-base.css"
