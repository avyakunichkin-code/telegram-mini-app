// Windows fallback for sync-lab.sh; same fonts and token sources.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const round = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(round, '../../..');
const source = path.join(repo, 'frontend-react/src');
const fonts = path.join(round, 'assets/fonts');
fs.mkdirSync(fonts, { recursive: true });
for (const name of fs.readdirSync(path.join(source, 'assets/fonts'))) {
  if (/^(nunito|manrope)-.*\.woff2$/.test(name)) {
    fs.copyFileSync(path.join(source, 'assets/fonts', name), path.join(fonts, name));
  }
}
const fontCss = fs.readFileSync(path.join(source, 'styles/fonts.css'), 'utf8').replaceAll('../assets/fonts/', './assets/fonts/');
const tokens = fs.readFileSync(path.join(source, 'styles/tokens.css'), 'utf8').replace(/^\uFEFF/, '');
fs.writeFileSync(path.join(round, 'lab-base.css'), '/* Generated by sync-lab.mjs; production fonts.css + tokens.css. */\n' + fontCss + '\n' + tokens);
console.log('Synced local fonts and tokens.');
