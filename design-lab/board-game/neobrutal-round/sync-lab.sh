#!/usr/bin/env bash
# Self-contained CSS для board-game/neobrutal-round (bash-only).
# lab-base.css = @font-face из prod (пути → ./assets/fonts/) + токены MQX v3 раунда.
set -euo pipefail

ROUND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$ROUND/../../.." && pwd)"
OUT="$ROUND/lab-base.css"
FONTS_CSS="$REPO/frontend-react/src/styles/fonts.css"
FONTS_DIR="$REPO/frontend-react/src/assets/fonts"
SOURCES=("$FONTS_CSS" "$ROUND/tokens-v3.css")

for src in "${SOURCES[@]}"; do
  if [[ ! -f "$src" ]]; then
    echo "sync-lab.sh: missing source: $src" >&2
    exit 1
  fi
done

mkdir -p "$ROUND/assets/fonts"
cp "$FONTS_DIR"/nunito-*.woff2 "$FONTS_DIR"/manrope-*.woff2 "$ROUND/assets/fonts/"

{
  cat <<'HDR'
/* Auto-generated by sync-lab.sh - do not edit by hand */
/* Round: board-game/neobrutal-round */
/* Sources: frontend-react/src/styles/fonts.css (пути шрифтов → ./assets/fonts/) + neobrutal-round/tokens-v3.css */

HDR
  sed "s#\.\./assets/fonts/#./assets/fonts/#g" "$FONTS_CSS"
  printf '\n'
  cat "$ROUND/tokens-v3.css"
  printf '\n'
} > "$OUT"

echo "OK: $OUT"
