#!/usr/bin/env bash
# Self-contained CSS для board-game/neobrutal-a-round (bash-only).
# lab-base.css = @font-face из prod (пути → ./assets/fonts/) + токены v3 и стили варианта A из neobrutal-round.
set -euo pipefail

ROUND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
THEME="$(cd "$ROUND/.." && pwd)"
REPO="$(cd "$ROUND/../../.." && pwd)"
OUT="$ROUND/lab-base.css"
FONTS_CSS="$REPO/frontend-react/src/styles/fonts.css"
FONTS_DIR="$REPO/frontend-react/src/assets/fonts"
SOURCES=("$FONTS_CSS" "$THEME/neobrutal-round/tokens-v3.css" "$THEME/neobrutal-round/styles.css")

for src in "${SOURCES[@]}"; do
  if [[ ! -f "$src" ]]; then
    echo "sync-lab.sh: missing source: $src" >&2
    exit 1
  fi
done

mkdir -p "$ROUND/assets/fonts"
cp "$FONTS_DIR"/nunito-*.woff2 "$FONTS_DIR"/manrope-*.woff2 "$ROUND/assets/fonts/"

{
  cat <<'HDR'
/* Auto-generated by sync-lab.sh - do not edit by hand */
/* Round: board-game/neobrutal-a-round */
/* Sources: frontend-react/src/styles/fonts.css (пути шрифтов → ./assets/fonts/) + neobrutal-round/tokens-v3.css + neobrutal-round/styles.css (вариант A — значения по умолчанию) */

HDR
  sed "s#\.\./assets/fonts/#./assets/fonts/#g" "$FONTS_CSS"
  printf '\n'
  cat "$THEME/neobrutal-round/tokens-v3.css"
  printf '\n'
  cat "$THEME/neobrutal-round/styles.css"
  printf '\n'
} > "$OUT"

echo "OK: $OUT"
