#!/usr/bin/env bash
set -euo pipefail
ROUND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$ROUND/../../.." && pwd)"
mkdir -p "$ROUND/assets/fonts"
cp "$REPO/frontend-react/src/assets/fonts/"*.woff2 "$ROUND/assets/fonts/"
{
  echo '/* Auto-generated by sync-lab.sh; do not edit by hand */'
  sed 's#../assets/fonts/#./assets/fonts/#g' "$REPO/frontend-react/src/styles/fonts.css"
  cat "$REPO/design-lab/board-game/neobrutal-round/tokens-v3.css"
} > "$ROUND/lab-base.css"
