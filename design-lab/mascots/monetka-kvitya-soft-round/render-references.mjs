import fs from 'node:fs/promises';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require=createRequire(new URL('../../../frontend-react/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const dir=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(dir,'../../..');
const ctx={window:{}};
vm.runInNewContext(await fs.readFile(path.join(repo,'design/system/illustrations/monetka.js'),'utf8'),ctx);
const coin=ctx.window.TH_MONETKA({face:'smile',arms:'wave',top:'НОВЫЙ ХОД',label:'Монетка'});
const receipt=await fs.readFile(path.join(repo,'design/system/assets/Monetka/kvitya-default.svg'),'utf8');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:900,height:600},deviceScaleFactor:2});
await page.setContent(`<style>html,body{margin:0;background:transparent}main{display:flex;align-items:end;justify-content:center;gap:90px;padding:45px;height:600px;box-sizing:border-box}svg{width:330px;height:480px}text{font-family:Arial,sans-serif}</style><main>${coin}${receipt}</main>`);
await page.screenshot({path:path.join(dir,'assets/reference/current.png'),omitBackground:true});
await browser.close();
console.log('Existing Monetka and Kvitya rendered unchanged.');
