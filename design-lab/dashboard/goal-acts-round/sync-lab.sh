#!/usr/bin/env bash
# Self-contained CSS + ассеты для dashboard/goal-acts-round (победа в два акта, bash-only).
set -euo pipefail

ROUND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LAB="$(cd "$ROUND/../.." && pwd)"
BG="$LAB/board-game"
OUT="$ROUND/lab-base.css"
# Токены ADR-014 + блоки BG-1 (цель) + экраны BG-2 (финал) + отличия prod дашборда и финала
SOURCES=(
  "$BG/styles.css"
  "$BG/logic-round/styles.css"
  "$BG/hybrid-round/styles.css"
  "$BG/screens-round/styles.css"
  "$LAB/dashboard/bg1-page-round/styles.css"
  "$LAB/run-finale/bg2-page-round/styles.css"
)

{
  cat <<'HDR'
/* Auto-generated by sync-lab.sh - do not edit by hand */
/* Round: dashboard/goal-acts-round */
/* Sources: board-game/styles.css + logic-round + hybrid-round + screens-round + dashboard/bg1-page-round + run-finale/bg2-page-round */

HDR
  for src in "${SOURCES[@]}"; do
    if [[ ! -f "$src" ]]; then
      echo "sync-lab.sh: missing source: $src" >&2
      exit 1
    fi
    cat "$src"
    printf '\n'
  done
} > "$OUT"

mkdir -p "$ROUND/assets"
cp "$LAB/dashboard/bg1-page-round/assets/monetka-mascot.png" "$ROUND/assets/"

echo "OK: $OUT"
