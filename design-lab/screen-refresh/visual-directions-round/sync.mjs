import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const round=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(round,'../../..');
const styles=path.join(repo,'frontend-react/src/styles');
fs.mkdirSync(path.join(round,'assets/fonts'),{recursive:true});
for(const name of fs.readdirSync(path.join(repo,'frontend-react/src/assets/fonts'))){
 if(/^(nunito|manrope)-.*\.woff2$/.test(name))fs.copyFileSync(path.join(repo,'frontend-react/src/assets/fonts',name),path.join(round,'assets/fonts',name));
}
const fonts=fs.readFileSync(path.join(styles,'fonts.css'),'utf8').replaceAll('../assets/fonts/','./assets/fonts/');
const tokens=fs.readFileSync(path.join(styles,'tokens.css'),'utf8').replace(/^\uFEFF/,'');
fs.writeFileSync(path.join(round,'lab-base.css'),'/* Auto-generated by sync.mjs; do not edit. */\n'+fonts+'\n'+tokens);
