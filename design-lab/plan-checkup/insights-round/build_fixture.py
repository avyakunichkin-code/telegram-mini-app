"""Собирает fixture.js из настоящего build_report на вымышленных семьях. Запуск: py -3 build_fixture.py"""
import json
import sys
from decimal import Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path[:0] = [str(ROOT / "apps/plan-api"), str(ROOT / "packages/fincore/src")]

from plan_api.analysis.report import build_report  # noqa: E402
from plan_api.demo import R, demo_data, demo_members  # noqa: E402
from plan_api.schemas import Checkup, CheckupData, ExpenseRow, GoalRow, IncomeRow, LiabilityRow, Member, SavingsRow  # noqa: E402

AS_OF = "2026-11"
main = Checkup(id="lab", entry_question="mortgage", as_of=AS_OF, members=demo_members(), data=demo_data(AS_OF))
strained = Checkup(
    id="lab", entry_question="resilience", as_of=AS_OF, members=[Member(id="m_me", label="Я")],
    data=CheckupData(
        incomes=[IncomeRow(member_id="m_me", amount=R(60_000, 80_000))],
        expenses=[
            ExpenseRow(category_key="food", title="Продукты и дом", amount=R(52_000)),
            ExpenseRow(category_key="cafe", title="Кафе и доставка", tier="want", amount=R(6_000)),
        ],
        liabilities=[
            LiabilityRow(id="card", kind="card", title="Кредитная карта", balance=Decimal(180_000), annual_rate=Decimal("34.9"), monthly_payment=Decimal(4_500)),
            LiabilityRow(id="loan", kind="consumer", title="Потребкредит", balance=Decimal(320_000), annual_rate=Decimal(19), monthly_payment=Decimal(16_000), term_months_left=26),
        ],
        savings=[SavingsRow(kind="account", amount=R(120_000))],
        goals=[GoalRow(id="g", title="Ремонт", target_amount=Decimal(200_000), target_month="2026-10", saved_amount=Decimal(10_000))],
    ),
)
cases = {"main": build_report(main), "strained": build_report(strained)}
payload = json.dumps({k: {"insights": v["insights"], "free_cashflow": v["free_cashflow"]} for k, v in cases.items()}, ensure_ascii=False, indent=1, default=float)
(HERE / "fixture.js").write_text(f"// Auto-generated by build_fixture.py; do not edit.\nwindow.FIXTURE = {payload}\n", encoding="utf-8")
