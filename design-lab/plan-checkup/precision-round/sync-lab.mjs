import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs'
const root=new URL('./',import.meta.url)
mkdirSync(new URL('./assets/',root),{recursive:true})
for(const weight of [400,700]){
 const name=`manrope-cyrillic-${weight}-normal.woff2`
 copyFileSync(new URL(`../../../frontend-react/src/assets/fonts/${name}`,root),new URL(`./assets/${name}`,root))
}
writeFileSync(new URL('./lab-base.css',root),'/* Auto-generated by sync-lab.mjs from styles.css; do not edit. */\n'+readFileSync(new URL('./styles.css',root),'utf8'))
const file=new URL('./index.html',root)
writeFileSync(file,readFileSync(file,'utf8').replace('href="./styles.css"','href="./lab-base.css"'))
console.log('Precision round: local fonts and lab-base.css synced.')
