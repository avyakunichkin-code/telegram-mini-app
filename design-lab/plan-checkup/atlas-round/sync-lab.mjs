import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
const assets = new URL('./assets/', import.meta.url)
mkdirSync(assets, { recursive: true })
for (const alphabet of ['cyrillic', 'latin']) {
  for (const weight of [400, 700]) {
    const name = `manrope-${alphabet}-${weight}-normal.woff2`
    copyFileSync(new URL(`../../../frontend-react/src/assets/fonts/${name}`, import.meta.url), new URL(name, assets))
  }
}
writeFileSync(new URL('./lab-base.css', import.meta.url), '/* Auto-generated by sync-lab.mjs from styles.css; do not edit. */\n' + readFileSync(new URL('./styles.css', import.meta.url), 'utf8'))
const index = new URL('./index.html', import.meta.url)
writeFileSync(index, readFileSync(index, 'utf8').replace('href="./styles.css"', 'href="./lab-base.css"'))
console.log('Atlas fonts and lab-base.css generated from local source.')
